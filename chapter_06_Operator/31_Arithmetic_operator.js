// arithmetic operator
// +, -, *, /, % (modulus), ** (exponentiation) 

let a = 10; b = 20;

let sum = a + b; // 30
let sub = a - b; // -10
let mul = a * b; // 200
let div = a / b; // 0.5
let mod = a % b; // 10 (remainder of division)




console.log("Sum:", sum); // 30
console.log("Subtraction:", sub);
console.log("Multiplication:", mul);
console.log("Division:", div);
console.log("Modulus:", mod); // 1 

console.log(100 % 2);
console.log(101 % 2);

