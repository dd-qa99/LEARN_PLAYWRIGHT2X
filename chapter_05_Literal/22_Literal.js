let age = "twenty five"; // String literal
let isStudent = true; // Boolean literal
let person = { name: "Alice", age: 30 }; // Object literal
let numbers = [1, 2, 3, 4, 5]; // Array literal
let pi = 3.14; // Number literal
let nullValue = null; // Null literal
let undefinedValue; // Undefined literal
let name = "john" // string literal
let address = '123 Main St, Anytown, USA'; // string literal

console.log(typeof age); // string
console.log(typeof isStudent); // boolean
console.log(typeof person); // object
console.log(typeof numbers); // object (arrays are a type of object in JavaScript)
console.log(typeof pi);     // number       
console.log(typeof nullValue); // object (a known JS quirk)
console.log(typeof undefinedValue); // undefined
console.log(typeof name); // string
console.log(typeof address); // string      