// ============================================================
// Backtick vs Single vs Double Quotes (Short)
// ============================================================

// Single quotes and double quotes are the same for normal strings.
let single = 'Hello';
let double = "Hello";

// Backticks are used for template literals and allow ${} interpolation.
let name = "Sam";
let backtick = `Hello, ${name}!`;

console.log(single);
console.log(double);
console.log(backtick);
