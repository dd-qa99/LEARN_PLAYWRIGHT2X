// comparision operator - boolean T/F
// ==, ===, !=, !==, >, <, >=, <=
// = assignment operator
// == loose comparision - equality operator (loose equality)
// === strict comparision - equality operator (strict equality)
// != loose inequality operator
// !== strict inequality operator

console.log(3 > 4); // false
console.log(3 < 4); // true
console.log(4 >= 4); // true  // 4>4 OR 4==4 or gate 
console.log(4 <= 4); // true
console.log(3 <= 4);